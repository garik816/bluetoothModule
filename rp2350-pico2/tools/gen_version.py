#!/usr/bin/env python3
"""Generate a new version header for EACH build, not just CMake configure."""
import os
import sys
from pathlib import Path

out = Path(sys.argv[1])
out.parent.mkdir(parents=True, exist_ok=True)
counter_path = out.parent / "build_version.count"
github_number = os.environ.get("GITHUB_RUN_NUMBER", "").strip()

if github_number.isdecimal():
    build = int(github_number)
    origin = "GitHub Actions"
else:
    try:
        build = int(counter_path.read_text(encoding="ascii").strip()) + 1
    except (FileNotFoundError, ValueError):
        build = 1
    counter_path.write_text(str(build), encoding="ascii")
    origin = "local build"

version = f"0.2.{build}"
out.write_text(
    "#pragma once\n"
    "/* Auto-generated by tools/gen_version.py. Do not edit. */\n"
    f'#define FIRMWARE_VERSION "{version}"\n'
    f"#define FIRMWARE_BUILD_NUMBER {build}\n",
    encoding="utf-8",
)
print(f"[VERSION] universal bluetooth module v.{version} ({origin})", flush=True)
